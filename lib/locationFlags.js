function flagIdFromLocationFlag(flagName, fallback = 4) {
  if (flagName == null) {
    return fallback;
  }
  if (typeof flagName === "number" && Number.isFinite(flagName)) {
    return Math.trunc(flagName);
  }
  const key = String(flagName);
  if (Object.prototype.hasOwnProperty.call(LOCATION_FLAG_TO_ID, key)) {
    return LOCATION_FLAG_TO_ID[key];
  }
  return fallback;
}

